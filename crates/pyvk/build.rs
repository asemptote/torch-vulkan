//! Compiles the C++ PyTorch backend (csrc/*.cpp) against the libtorch that
//! ships with the target Python's `torch` package, and links it in.
//!
//! The Python interpreter is taken from PYO3_PYTHON (set by maturin), then
//! VIRTUAL_ENV, then `python` on PATH; TORCH_DIR overrides the torch location
//! (with TORCH_CXX11_ABI=0/1 giving its libstdc++ ABI on Linux, default 1).
//!
//! Also generates `opcodes.h` (namespace vk::op) from the shaders' operation
//! codes in crates/vkcore/shaders/opcodes.txt.

use std::path::{Path, PathBuf};
use std::process::Command;

fn python() -> PathBuf {
    if let Some(p) = std::env::var_os("PYO3_PYTHON") {
        return p.into();
    }
    if let Some(venv) = std::env::var_os("VIRTUAL_ENV") {
        let exe = Path::new(&venv).join(if cfg!(windows) { "Scripts/python.exe" } else { "bin/python" });
        if exe.exists() {
            return exe;
        }
    }
    "python".into()
}

/// The torch package directory and whether libtorch uses the C++11 libstdc++ ABI.
fn torch() -> (PathBuf, bool) {
    if let Some(dir) = std::env::var_os("TORCH_DIR") {
        return (dir.into(), std::env::var("TORCH_CXX11_ABI").map_or(true, |v| v != "0"));
    }
    let script = "import os, torch; print(os.path.dirname(torch.__file__)); print(int(torch._C._GLIBCXX_USE_CXX11_ABI))";
    let out = Command::new(python())
        .args(["-c", script])
        .output()
        .expect("could not run Python to locate torch; set TORCH_DIR");
    assert!(out.status.success(), "importing torch failed: {}", String::from_utf8_lossy(&out.stderr));
    let text = String::from_utf8(out.stdout).unwrap();
    let mut lines = text.lines();
    let dir = PathBuf::from(lines.next().unwrap().trim());
    let abi = lines.next().is_none_or(|l| l.trim() != "0");
    (dir, abi)
}

/// Writes OUT_DIR/opcodes.h from `opcodes.txt` lines `FAMILY NAME CODE`.
fn write_opcodes(out_dir: &Path) {
    let src = Path::new("../vkcore/shaders/opcodes.txt");
    println!("cargo:rerun-if-changed={}", src.display());
    let text = std::fs::read_to_string(src).expect("reading opcodes.txt");
    let mut header = String::from(
        "// Generated by crates/pyvk/build.rs from crates/vkcore/shaders/opcodes.txt.\n\
         #pragma once\n#include <cstdint>\nnamespace vk::op {\n",
    );
    for line in text.lines().map(str::trim).filter(|l| !l.is_empty() && !l.starts_with('#')) {
        let parts: Vec<&str> = line.split_whitespace().collect();
        assert!(parts.len() == 3, "opcodes.txt: expected `FAMILY NAME CODE`, got `{line}`");
        header.push_str(&format!("constexpr uint32_t {}_{} = {};\n", parts[0], parts[1], parts[2]));
    }
    header.push_str("}  // namespace vk::op\n");
    let path = out_dir.join("opcodes.h");
    if std::fs::read_to_string(&path).ok().as_deref() != Some(header.as_str()) {
        std::fs::write(&path, header).expect("writing opcodes.h");
    }
}

fn main() {
    println!("cargo:rerun-if-changed=csrc");
    println!("cargo:rerun-if-env-changed=TORCH_DIR");
    println!("cargo:rerun-if-env-changed=PYO3_PYTHON");
    println!("cargo:rerun-if-env-changed=TORCH_CXX11_ABI");
    let (torch, cxx11_abi) = torch();
    let include = torch.join("include");
    let out_dir = PathBuf::from(std::env::var("OUT_DIR").unwrap());
    write_opcodes(&out_dir);

    let mut build = cc::Build::new();
    build
        .cpp(true)
        .files([
            "csrc/backend.cpp",
            "csrc/launch.cpp",
            "csrc/ops.cpp",
            "csrc/elementwise.cpp",
            "csrc/indexing.cpp",
            "csrc/sorting.cpp",
            "csrc/random.cpp",
            "csrc/convolution.cpp",
            "csrc/normalization.cpp",
            "csrc/reduce.cpp",
            "csrc/linalg.cpp",
            "csrc/fft.cpp",
            "csrc/dense.cpp",
            "csrc/special.cpp",
            "csrc/pool.cpp",
        ])
        // Every object file registers aten kernels from static initializers
        // and nothing references them by symbol, so link the archive whole.
        .link_lib_modifier("+whole-archive")
        .include(&out_dir)
        .include(&include)
        .include(include.join("torch/csrc/api/include"))
        .define("NOMINMAX", None)
        .define("_CRT_SECURE_NO_WARNINGS", None)
        .warnings(false);
    if build.get_compiler().is_like_msvc() {
        build.flags(["/std:c++20", "/EHsc", "/Zc:__cplusplus", "/permissive-", "/bigobj", "/utf-8"]);
    } else {
        build.flags(["-std=c++20", "-fvisibility=hidden"]);
        build.define("_GLIBCXX_USE_CXX11_ABI", if cxx11_abi { "1" } else { "0" });
    }
    build.compile("vk_backend");

    let lib = torch.join("lib");
    println!("cargo:rustc-link-search=native={}", lib.display());
    if !cfg!(windows) {
        // Found at run time even when torch is not imported first.
        println!("cargo:rustc-link-arg=-Wl,-rpath,{}", lib.display());
    }
    for lib in ["c10", "torch_cpu", "torch"] {
        println!("cargo:rustc-link-lib=dylib={lib}");
    }
}
